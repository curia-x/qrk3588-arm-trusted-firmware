#ifndef QRK3588_EMMC_REGS_H
#define QRK3588_EMMC_REGS_H

#include <lib/utils_def.h>

/* RK3588 TRM v1.0 Part 1: address map, CRU and BUS_IOC chapters. */
#define EMMC_BASE			UL(0xfe2e0000)
#define EMMC_CRU_BASE			UL(0xfd7c0000)
#define EMMC_CLKSEL			(EMMC_CRU_BASE + U(0x0434))
#define EMMC_CLKGATE			(EMMC_CRU_BASE + U(0x087c))
#define EMMC_CLK_SOURCE_MASK		GENMASK_32(15, 14)
#define EMMC_CLK_SOURCE_OSC		(U(2) << 14)
#define EMMC_CLK_DIV_MASK		GENMASK_32(13, 8)
#define EMMC_CLK_DIV_SHIFT		8U
#define EMMC_GATE_HCLK			BIT_32(4)
#define EMMC_GATE_ACLK			BIT_32(5)
#define EMMC_GATE_CCLK			BIT_32(6)
#define EMMC_GATE_BCLK			BIT_32(7)
#define EMMC_GATE_TMCLK			BIT_32(8)
#define EMMC_CLOCK_GATES			(EMMC_GATE_HCLK | EMMC_GATE_ACLK | \
					 EMMC_GATE_CCLK | EMMC_GATE_BCLK | \
					 EMMC_GATE_TMCLK)
#define EMMC_SYS_GRF_CON10		UL(0xfd58c328)
#define EMMC_GRF_CLOCK_BYPASS		BIT_32(9)
#define EMMC_GRF_CLOCK_STABLE		BIT_32(8)
#define EMMC_IOC_CMD_CLK			UL(0xfd5f8040)
#define EMMC_IOC_DATA0			UL(0xfd5f8058)
#define EMMC_PIN_FUNCTION		U(1)
#define EMMC_CMD_MUX_MASK		GENMASK_32(3, 0)
#define EMMC_CLK_MUX_MASK		GENMASK_32(7, 4)
#define EMMC_CLK_MUX_SHIFT		4U
#define EMMC_DATA0_MUX_MASK		GENMASK_32(3, 0)
#define EMMC_WRITE_ENABLE_SHIFT		16U

/* TRM Part 2, chapter 4: access widths are part of the register ABI. */
#define EMMC_BLOCK_SIZE			U(0x004) /* 16-bit */
#define EMMC_BLOCK_COUNT		U(0x006) /* 16-bit */
#define EMMC_ARGUMENT			U(0x008) /* 32-bit */
#define EMMC_TRANSFER_MODE		U(0x00c) /* 16-bit */
#define EMMC_COMMAND			U(0x00e) /* 16-bit */
#define EMMC_RESPONSE			U(0x010) /* 32-bit */
#define EMMC_BUFFER			U(0x020) /* 32-bit */
#define EMMC_PRESENT_STATE		U(0x024) /* 32-bit */
#define EMMC_HOST_CONTROL		U(0x028) /* 8-bit */
#define EMMC_POWER_CONTROL		U(0x029) /* 8-bit, only bit 0 writable */
#define EMMC_CLOCK_CONTROL		U(0x02c) /* 16-bit */
#define EMMC_TIMEOUT_CONTROL		U(0x02e) /* 8-bit */
#define EMMC_SOFTWARE_RESET		U(0x02f) /* 8-bit */
#define EMMC_NORMAL_STATUS		U(0x030) /* 16-bit, W1C */
#define EMMC_ERROR_STATUS		U(0x032) /* 16-bit, W1C */
#define EMMC_NORMAL_ENABLE		U(0x034) /* 16-bit */
#define EMMC_ERROR_ENABLE		U(0x036) /* 16-bit */
#define EMMC_NORMAL_SIGNAL		U(0x038) /* 16-bit */
#define EMMC_ERROR_SIGNAL		U(0x03a) /* 16-bit */
#define EMMC_HOST_CONTROL2		U(0x03e) /* 16-bit */
#define EMMC_CARD_CONTROL		U(0x52c) /* 16-bit */
#define EMMC_DLL_CONTROL		U(0x800) /* 32-bit */
#define EMMC_DLL_RECEIVE		U(0x804) /* 32-bit */
#define EMMC_DLL_TRANSMIT		U(0x808) /* 32-bit */
#define EMMC_DLL_COMMAND_OUT		U(0x810) /* 32-bit */

#define EMMC_INHIBIT_COMMAND		BIT_32(0)
#define EMMC_INHIBIT_DATA		BIT_32(1)
#define EMMC_BUS_POWER_ON		BIT_32(0)
#define EMMC_INTERNAL_CLOCK_ON		BIT_32(0)
#define EMMC_INTERNAL_CLOCK_STABLE	BIT_32(1)
#define EMMC_CARD_CLOCK_ON		BIT_32(2)
#define EMMC_RESET_ALL			BIT_32(0)
#define EMMC_RESET_COMMAND		BIT_32(1)
#define EMMC_RESET_DATA			BIT_32(2)
#define EMMC_TIMEOUT_MAX		U(14) /* TMCLK * 2^(13 + 14) */
#define EMMC_CARD_IS_EMMC		BIT_32(0)
#define EMMC_CARD_RESET_RELEASED		BIT_32(2)
#define EMMC_DLL_BYPASS			BIT_32(24)
#define EMMC_RX_ORIGINAL_CLOCK		BIT_32(29)
#define EMMC_TX_INVERTED_CLOCK		U(0)
#define EMMC_CMD_RISING_EDGE		U(0)
#define EMMC_HOST_LEGACY_1BIT		U(0)
#define EMMC_HOST_NO_PRESET		U(0)

#define EMMC_COMMAND_INDEX_SHIFT		8U
#define EMMC_COMMAND_TYPE_MASK		GENMASK_32(7, 6)
#define EMMC_COMMAND_NORMAL		U(0)
#define EMMC_COMMAND_DATA		BIT_32(5)
#define EMMC_COMMAND_INDEX_CHECK		BIT_32(4)
#define EMMC_COMMAND_CRC_CHECK		BIT_32(3)
#define EMMC_RESPONSE_NONE		U(0)
#define EMMC_RESPONSE_LONG		U(1)
#define EMMC_RESPONSE_SHORT		U(2)
#define EMMC_RESPONSE_BUSY		U(3)
#define EMMC_RESPONSE_MASK		GENMASK_32(1, 0)
#define EMMC_RESPONSE_R1			(EMMC_RESPONSE_SHORT | \
		EMMC_COMMAND_INDEX_CHECK | EMMC_COMMAND_CRC_CHECK)
#define EMMC_RESPONSE_R1B		(EMMC_RESPONSE_BUSY | \
		EMMC_COMMAND_INDEX_CHECK | EMMC_COMMAND_CRC_CHECK)
#define EMMC_RESPONSE_R2			(EMMC_RESPONSE_LONG | EMMC_COMMAND_CRC_CHECK)
#define EMMC_RESPONSE_R3			EMMC_RESPONSE_SHORT
#define EMMC_TRANSFER_READ		BIT_32(4)
#define EMMC_TRANSFER_WRITE		U(0)
#define EMMC_EVENT_COMMAND		BIT_32(0)
#define EMMC_EVENT_TRANSFER		BIT_32(1)
#define EMMC_EVENT_WRITE_READY		BIT_32(4)
#define EMMC_EVENT_READ_READY		BIT_32(5)
#define EMMC_EVENT_ERROR			BIT_32(15)
#define EMMC_PIO_EVENTS			(EMMC_EVENT_COMMAND | EMMC_EVENT_TRANSFER | \
					 EMMC_EVENT_WRITE_READY | EMMC_EVENT_READ_READY)
#define EMMC_ERROR_COMMAND_TIMEOUT	BIT_32(0)
#define EMMC_ERROR_COMMAND_CRC		BIT_32(1)
#define EMMC_ERROR_COMMAND_END		BIT_32(2)
#define EMMC_ERROR_COMMAND_INDEX		BIT_32(3)
#define EMMC_ERROR_DATA_TIMEOUT		BIT_32(4)
#define EMMC_ERROR_DATA_CRC		BIT_32(5)
#define EMMC_ERROR_DATA_END		BIT_32(6)
#define EMMC_PIO_ERRORS			(EMMC_ERROR_COMMAND_TIMEOUT | \
		EMMC_ERROR_COMMAND_CRC | EMMC_ERROR_COMMAND_END | \
		EMMC_ERROR_COMMAND_INDEX | EMMC_ERROR_DATA_TIMEOUT | \
		EMMC_ERROR_DATA_CRC | EMMC_ERROR_DATA_END)

#endif /* QRK3588_EMMC_REGS_H */
