/* Write-mask field helper.  width must be <= 16. */
#define QRK3588_WIDTH_MASK(width)          ((U(1) << (width)) - U(1))
#define QRK3588_FIELD_MASK(field) \
	(QRK3588_WIDTH_MASK(QRK3588_##field##_WIDTH) << QRK3588_##field##_SHIFT)
#define QRK3588_FIELD_VALUE(field, value) \
	(((uint32_t)(value) & QRK3588_WIDTH_MASK(QRK3588_##field##_WIDTH)) \
	 << QRK3588_##field##_SHIFT)
#define QRK3588_FIELD(field, value) \
	((QRK3588_FIELD_MASK(field) << 16) | QRK3588_FIELD_VALUE(field, (value)))

#define QRK3588_DIV_ENCODE(divisor)        ((uint32_t)(divisor) - U(1))

